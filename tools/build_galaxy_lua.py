"""Writes src/galaxy.lua, the galaxy map the mod draws, from the Obsidian Commander map data.

Usage: python -P tools/build_galaxy_lua.py [<galaxy-hd2.json>]

The default source is ObsidianCommander/data/galaxy-hd2.json beside this workspace's Mods folder. The
server, the war screens and this mod draw from the same file, so a planet number means the same planet
everywhere. Planet numbers start at 0 on the server; the Lua lists start at 1, so planet n is planets[n + 1].
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
DEFAULT = HERE.parent.parent / "ProjectObsidian" / "ObsidianCommander" / "data" / "galaxy-hd2.json"


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def nums(values):
    return ",".join(num(v) for v in values)


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    g = json.loads(src.read_text(encoding="utf-8"))
    out = []
    w = out.append
    w("-- Generated by tools/build_galaxy_lua.py from the Obsidian Commander map data (data/galaxy-hd2.json).")
    w("-- Don't edit: rebuild it. The HELLDIVERS 2 galaxy layout: names, positions, sectors and supply lines.")
    w("-- Planet ids count from 0 as on the server, so planet n is planets[n + 1]. Factions: 0 Super Earth,")
    w("-- 1 bugs, 2 cyborgs, 3 illuminates. env: 0 desert, 1 forest, 2 snow, 3 lava, 4 city.")
    w("return {")
    w(f"\tgalaxy = {lua_str(g['galaxy'])}, version = {g['version']}, rim = {num(g['rim'])},")
    homes = ", ".join(f"[{['superearth', 'bugs', 'cyborgs', 'illuminates'].index(k)}] = {v}" for k, v in g["homes"].items())
    w(f"\thomes = {{ {homes} }},")
    w("\tsectors = {")
    for s in g["sectors"]:
        w(f"\t\t{{ id = {s['id']}, name = {lua_str(s['name'])}, x = {num(s['x'])}, y = {num(s['y'])}, owner = {s['owner']}, planets = {{ {','.join(str(p) for p in s['planets'])} }} }},")
    w("\t},")
    w("\tplanets = {")
    for p in g["planets"]:
        hz = ", ".join(lua_str(h) for h in p.get("hazards", []))
        w(f"\t\t{{ id = {p['id']}, name = {lua_str(p['name'])}, sector = {p['sector']}, x = {num(p['x'])}, y = {num(p['y'])}, "
          f"env = {p['env']}, biome = {lua_str(p['biome'])}, owner = {p['owner']}, hazards = {{ {hz} }}, cell = {{ {nums(p['cell'])} }} }},")
    w("\t},")
    flat = [v for pair in g["links"] for v in pair]
    w(f"\tlinks = {{ {','.join(str(v) for v in flat)} }},")
    borders = []
    for b in g["borders"]:
        borders += [num(b[0]), num(b[1]), num(b[2]), num(b[3]), str(b[4]), str(b[5])]
    w(f"\tborders = {{ {','.join(borders)} }},")
    w("}")
    dest = HERE / "src" / "galaxy.lua"
    with open(dest, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{dest}: {len(g['planets'])} planets, {len(g['sectors'])} sectors, {len(g['links'])} links, "
          f"{len(g['borders'])} border edges, {dest.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
